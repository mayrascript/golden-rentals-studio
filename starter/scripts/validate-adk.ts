import assert from 'node:assert/strict';
import { FunctionTool, SkillToolset } from '@google/adk';
import { createTeam } from '../apps/server/src/agents/team.js';
const team = await createTeam({ apiKey: 'offline-validation-only', textModel: 'gemini-3.8-flash', context: () => { throw new Error('Esta validación no puede llamar al modelo.'); }, generateImage: async () => { throw new Error('Esta validación no genera imágenes.'); } });
assert.deepEqual(Object.keys(team), ['strategist', 'copywriter', 'designer', 'editor']);
assert.equal(team.copywriter.tools.length, 1); assert.equal(team.designer.tools.length, 1);
const skillTools = team.copywriter.tools[0]; assert.ok(skillTools instanceof SkillToolset);
assert.ok((await skillTools.getTools()).some(tool => tool.name === 'load_skill'));
assert.ok(skillTools.getSkill('instagram-copy'));
const imageTool = team.designer.tools[0]; assert.ok(imageTool instanceof FunctionTool);
assert.equal(imageTool._getDeclaration().name, 'generate_campaign_image');
console.log('ADK verificado sin red: cuatro agentes reales instanciados; skill local cargada y herramienta de imágenes registrada. No se ejecutó inferencia ni generación real.');
